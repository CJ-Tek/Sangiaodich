import { routing, type AppLocale } from '@/lib/i18n/routing';

const FALLBACK_SITE_URL = 'https://sangiaodich.vercel.app';

/** Canonical origin without trailing slash. Set NEXT_PUBLIC_APP_URL once a custom domain exists. */
export function siteUrl(): string {
  const raw = process.env.NEXT_PUBLIC_APP_URL?.trim();
  return (raw || FALLBACK_SITE_URL).replace(/\/+$/, '');
}

/** Path for a locale under `localePrefix: 'as-needed'` (default locale has no prefix). */
export function localizedPath(locale: AppLocale, path = '/'): string {
  const normalized = path.startsWith('/') ? path : `/${path}`;
  if (locale === routing.defaultLocale) return normalized;
  return normalized === '/' ? `/${locale}` : `/${locale}${normalized}`;
}

export function absoluteUrl(locale: AppLocale, path = '/'): string {
  return `${siteUrl()}${localizedPath(locale, path)}`;
}

/** hreflang map for `alternates.languages`, including x-default. */
export function languageAlternates(path = '/'): Record<string, string> {
  const entries = routing.locales.map((locale) => [locale, absoluteUrl(locale, path)]);
  return {
    ...Object.fromEntries(entries),
    'x-default': absoluteUrl(routing.defaultLocale, path),
  };
}

export const openGraphLocale: Record<AppLocale, string> = {
  vi: 'vi_VN',
  en: 'en_US',
};

/** Static share image generated by scripts/generate-og-images.mjs. */
export function ogImage(locale: AppLocale, alt: string) {
  return { url: `/og/vbnb-og-${locale}.png`, width: 1200, height: 630, alt };
}

export function serializeJsonLd(data: unknown): string {
  return JSON.stringify(data).replace(/</g, '\\u003c');
}
